import { loadLibrary } from '../core/libraryLoader.js';

export default class PDFPage {
  constructor() {
    this._pdfDoc = null;
    this._page = 1;
    this._rendering = false;
    this._handlers = [];
  }

  async init() {
    await loadLibrary('pdfjs');
    await loadLibrary('jspdf');
    if (window.pdfjsLib) {
      pdfjsLib.GlobalWorkerOptions.workerSrc = 'https://cdn.jsdelivr.net/npm/pdfjs-dist@4.9.155/build/pdf.worker.min.mjs';
    }
    this._bindControls();
  }

  _bindControls() {
    this._on(document.getElementById('pdf-load-url'), 'click', () => this._loadURL());
    this._on(document.getElementById('pdf-prev'),     'click', () => this._navPage(-1));
    this._on(document.getElementById('pdf-next'),     'click', () => this._navPage(1));
    this._on(document.getElementById('pdf-generate'), 'click', () => this._generate());
  }

  async _loadURL() {
    const urlEl = document.getElementById('pdf-url');
    const url   = urlEl?.value?.trim() || 'https://www.w3.org/WAI/WCAG21/wcag21-errata-20230106.pdf';
    const status = document.getElementById('pdf-status');
    if (status) status.textContent = 'Loading PDF…';
    try {
      this._pdfDoc = await pdfjsLib.getDocument({
        url,
        cMapUrl: 'https://cdn.jsdelivr.net/npm/pdfjs-dist@4.9.155/cmaps/',
        cMapPacked: true,
      }).promise;
      this._page = 1;
      if (status) status.textContent = `Loaded — ${this._pdfDoc.numPages} pages`;
      this._renderPage();
    } catch (err) {
      if (status) status.textContent = `Failed: ${err.message}`;
    }
  }

  async _renderPage() {
    if (!this._pdfDoc || this._rendering) return;
    this._rendering = true;
    const canvas  = document.getElementById('pdf-canvas');
    const numInfo = document.getElementById('pdf-num');
    if (!canvas) { this._rendering = false; return; }
    const page    = await this._pdfDoc.getPage(this._page);
    const vp      = page.getViewport({ scale: 1.5 });
    canvas.width  = vp.width;
    canvas.height = vp.height;
    await page.render({ canvasContext: canvas.getContext('2d'), viewport: vp }).promise;
    this._rendering = false;
    if (numInfo) numInfo.textContent = `Page ${this._page} / ${this._pdfDoc.numPages}`;
  }

  _navPage(dir) {
    if (!this._pdfDoc) return;
    const np = this._page + dir;
    if (np >= 1 && np <= this._pdfDoc.numPages) { this._page = np; this._renderPage(); }
  }

  _generate() {
    if (!window.jspdf) return;
    const { jsPDF } = jspdf;
    const doc = new jsPDF();
    doc.setFontSize(22);
    doc.setTextColor(56, 189, 248);
    doc.text('Frontend Nexus', 20, 30);
    doc.setFontSize(12);
    doc.setTextColor(100, 116, 139);
    doc.text('Generated by jsPDF — no server required.', 20, 44);
    doc.setFontSize(11);
    doc.setTextColor(30, 41, 59);
    const lines = [
      `Date: ${new Date().toLocaleDateString()}`,
      `Libraries: 47+`,
      `Browser APIs: 27`,
      `Demos: 100+`,
      `Framework dependencies: 0`,
      '',
      'This document was generated entirely in the browser',
      'using jsPDF running from a CDN — zero npm, zero build tools.',
    ];
    lines.forEach((ln, i) => doc.text(ln, 20, 60 + i * 9));
    doc.save('frontend-nexus.pdf');
  }

  _on(el, evt, fn) { if (!el) return; el.addEventListener(evt, fn); this._handlers.push({ el, evt, fn }); }

  destroy() {
    this._pdfDoc = null;
    this._handlers.forEach(({ el, evt, fn }) => el?.removeEventListener(evt, fn));
    this._handlers = [];
  }
}
